function hostOf(raw) {
  try { return new URL(/^https?:/i.test(raw) ? raw : 'https://' + raw).hostname.replace(/^www\./, '').toLowerCase(); } catch { return ''; }
}
const allowedHost = (h) => ALLOWED_EXTERNAL.some((d) => h === d || h.endsWith('.' + d));

/**
 * Последняя линия защиты: убирает ссылки на сторонние сайты и упоминания
 * сторонних площадок. Если ответ после этого уводит «в другое место» —
 * заменяет его на ответ в рамках платформы.
 */
export function enforceSiteScope(text, { publicMode = false } = {}) {
  if (!text || typeof text !== 'string') return text;
  let removed = 0;
  // markdown-ссылки [текст](url) на внешние домены → просто текст
  let out = text.replace(/\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/giu, (m, label, url) => {
    if (allowedHost(hostOf(url))) return m;
    removed += 1; return label;
  });
  out = out.replace(URL_RE, (m) => {
    const h = hostOf(m);
    if (!h || allowedHost(h)) return m;
    removed += 1; return '';
  });
  out = out.replace(EXTERNAL_BRANDS, () => { removed += 1; return ''; });
  if (!removed) return text;
  out = out.replace(/\(\s*\)/g, '').replace(/[ \t]{2,}/g, ' ').replace(/ +([,.;:!?])/g, '$1').replace(/^[ \t]*[-*•]\s*[,.;:]?\s*$/gmu, '').replace(/\n{3,}/g, '\n\n').trim();
  const sends = /(другие|сторонн|специализированн)[а-я]*\s+(сайт|ресурс|сервис|площадк|приложени)|поищ[а-я]*\s+в\s+интернет|воспользу[а-я]*\s+(сайт|сервис)|(посмотр|загляни|зайди|обратись)[а-я]*\s+(на|в)\s+(сайт|сервис|приложени)/iu;
  if (sends.test(out) || out.length < 40) {
    return `${OFF_TOPIC_REPLY}\n\nПо поиску работы: открой «Биржу заказов» (${publicMode ? '/marketplace' : '/app/marketplace'}) и «Вакансии» (${publicMode ? '/jobs' : '/app/vacancies'}) — или попроси меня: «подбери заказы под мой профиль».`;
  }
  return out;
}

