const URL_RE = /\bhttps?:\/\/[^\s)\]>"']+|\b(?:www\.)?[a-z0-9-]+(?:\.[a-z0-9-]+)*\.(?:ru|com|рф|net|org|io|me|su|pro|ua|by|kz)\b(?:\/[^\s)\]>"']*)?/giu;
