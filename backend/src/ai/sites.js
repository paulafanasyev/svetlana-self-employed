/** Скрыть телефоны и e-mail до отправки во внешнюю модель (детский режим и публичные сайты). */
export function redactPersonal(text) {
  return String(text ?? '')
    .replace(/[\w.+-]+@[\w-]+\.[\w.-]+/g, '[скрыто]')
    .replace(/(?:\+7|8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}/g, '[скрыто]')
    .replace(/\b\d{10,}\b/g, '[скрыто]');
}

/** Ответ ребёнку без markdown и не длиннее 900 символов. */
export function tidyForChild(text) {
  let out = String(text ?? '').replace(/[*_#`>]+/g, '').trim();
  if (out.length > 900) out = out.slice(0, 900).replace(/\s+\S*$/, '') + '…';
  return out;
}
