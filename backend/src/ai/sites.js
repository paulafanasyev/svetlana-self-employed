const URL_RE = /\bhttps?:\/\/[^\s)\]>"']+|\b(?:www\.)?[a-z0-9-]+(?:\.[a-z0-9-]+)*\.(?:ru|com|рф|net|org|io|me|su|tv|app|pro|ua|by|kz)\b(?:\/[^\s)\]>"']*)?/giu;
const COMMON_BRANDS = ['google', 'гугл[а-я]*', 'yandex', 'яндекс[а-я]*', 'youtube', 'ютуб[а-я]*', 'telegram', 'телеграм[а-я]*', 'вконтакте', 'whatsapp', 'ватсап[а-я]*', 'chatgpt', 'чатгпт', 'gpt-?\\d*'];

function hostOf(raw) {
  try { return new URL(/^https?:/i.test(raw) ? raw : 'https://' + raw).hostname.replace(/^www\./, '').toLowerCase(); } catch { return ''; }
}

/** Фабрика «последней линии защиты»: убирает чужие ссылки и бренды; если ответ уводит наружу — заменяет. */
function makeEnforcer({ allowed = [], brands = [], offTopic, strict = false }) {
  const brandRe = new RegExp(`(?<![\\p{L}\\d])(${[...COMMON_BRANDS, ...brands].join('|')})(?![\\p{L}\\d])`, 'giu');
  const ok = (h) => allowed.some((d) => h === d || h.endsWith('.' + d));
  const sends = /(другие|сторонн|специализированн)[а-я]*\s+(сайт|ресурс|сервис|площадк|приложени)|поищ[а-я]*\s+в\s+интернет|(посмотр|загляни|зайди|обратись|скачай)[а-я]*\s+(на|в)\s+(сайт|сервис|приложени|магазин)/iu;
  return (text) => {
    if (!text || typeof text !== 'string') return offTopic;
    let removed = 0;
    let out = text.replace(/\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/giu, (m, label, url) => {
      if (ok(hostOf(url))) return m;
      removed += 1; return label;
    });
    out = out.replace(URL_RE, (m) => {
      const h = hostOf(m);
      if (!h || ok(h)) return m;
      removed += 1; return '';
    });
    out = out.replace(brandRe, () => { removed += 1; return ''; });
    if (!removed) return text;
    out = out.replace(/\(\s*\)/g, '').replace(/[ \t]{2,}/g, ' ').replace(/ +([,.;:!?])/g, '$1').replace(/\n{3,}/g, '\n\n').trim();
    if (strict || sends.test(out) || out.length < 40) return offTopic;
    return out;
  };
}

